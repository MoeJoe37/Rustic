//! Original implementation of the WHATWG Encoding Standard.
//!
//! [`Encoding`] covers every encoding the standard defines, and
//! [`Encoding::for_label`] is its "get an encoding" over the full label table.
//! [`Decoder`] runs an encoding's decoder over a byte stream in chunks, with
//! the "replacement" or "fatal" error mode, and [`Encoder`] runs an encoder one
//! scalar value at a time so that callers such as URL percent-encoding can
//! handle unmappable characters themselves. The legacy hooks [`decode`],
//! [`bom_sniff`] and [`encode`] and the UTF-8 hooks complete the "Hooks for
//! standards" section.
//!
//! The label table and every index are generated by
//! `tools/generate_encoding_data.py` from a pinned revision of the standard
//! ([`ENCODING_STANDARD_REVISION`]). Multi-byte indexes are stored as
//! little-endian arrays and read without allocation; the reverse indexes that
//! the multi-byte encoders need are built once, on first use, per index.
//!
//! The crate has no dependencies and performs no I/O. Work is linear in the
//! input; callers bound the input size.

#![warn(missing_docs)]

mod decoder;
mod encoder;
mod index;
mod tables;

pub use decoder::{DecodeError, Decoder, DecoderErrorMode};
pub use encoder::Encoder;
pub use tables::ENCODING_STANDARD_REVISION;

/// An encoding defined by the Encoding Standard.
///
/// The discriminants follow the standard's order, so [`Encoding::all`] and
/// sorting by `Encoding` agree with the table in its "Names and labels"
/// section.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Encoding {
    /// UTF-8, the encoding for all new content.
    Utf8,
    /// IBM866.
    Ibm866,
    /// ISO-8859-2.
    Iso8859_2,
    /// ISO-8859-3.
    Iso8859_3,
    /// ISO-8859-4.
    Iso8859_4,
    /// ISO-8859-5.
    Iso8859_5,
    /// ISO-8859-6.
    Iso8859_6,
    /// ISO-8859-7.
    Iso8859_7,
    /// ISO-8859-8 (visual order).
    Iso8859_8,
    /// ISO-8859-8-I (logical order; same index as ISO-8859-8).
    Iso8859_8I,
    /// ISO-8859-10.
    Iso8859_10,
    /// ISO-8859-13.
    Iso8859_13,
    /// ISO-8859-14.
    Iso8859_14,
    /// ISO-8859-15.
    Iso8859_15,
    /// ISO-8859-16.
    Iso8859_16,
    /// KOI8-R.
    Koi8R,
    /// KOI8-U.
    Koi8U,
    /// macintosh.
    Macintosh,
    /// windows-874.
    Windows874,
    /// windows-1250.
    Windows1250,
    /// windows-1251.
    Windows1251,
    /// windows-1252, which the `latin1`, `ascii` and `iso-8859-1` labels select.
    Windows1252,
    /// windows-1253.
    Windows1253,
    /// windows-1254.
    Windows1254,
    /// windows-1255.
    Windows1255,
    /// windows-1256.
    Windows1256,
    /// windows-1257.
    Windows1257,
    /// windows-1258.
    Windows1258,
    /// x-mac-cyrillic.
    XMacCyrillic,
    /// GBK: gb18030's decoder, an encoder without four-byte sequences.
    Gbk,
    /// gb18030.
    Gb18030,
    /// Big5 with the HKSCS extensions.
    Big5,
    /// EUC-JP.
    EucJp,
    /// ISO-2022-JP.
    Iso2022Jp,
    /// Shift_JIS.
    ShiftJis,
    /// EUC-KR (Windows code page 949).
    EucKr,
    /// replacement: decodes any non-empty input to one U+FFFD.
    Replacement,
    /// UTF-16BE.
    Utf16Be,
    /// UTF-16LE, which the `utf-16` label selects.
    Utf16Le,
    /// x-user-defined.
    XUserDefined,
}

impl Encoding {
    /// Every encoding, in the standard's order.
    pub fn all() -> &'static [Encoding] {
        &tables::ALL
    }

    /// "Get an encoding": the encoding `label` names, after removing leading
    /// and trailing ASCII whitespace and matching ASCII case-insensitively.
    pub fn for_label(label: &str) -> Option<Encoding> {
        Self::for_label_bytes(label.as_bytes())
    }

    /// [`Encoding::for_label`] for a label that is not known to be UTF-8,
    /// such as an HTTP `charset` parameter or a `<meta>` prescan result.
    pub fn for_label_bytes(label: &[u8]) -> Option<Encoding> {
        let label = trim_ascii_whitespace(label);
        // Every label is shorter than 32 bytes (a unit test checks this), so
        // anything longer cannot match.
        if label.is_empty() || label.len() > 32 {
            return None;
        }
        let mut lower = [0u8; 32];
        for (slot, byte) in lower.iter_mut().zip(label) {
            *slot = byte.to_ascii_lowercase();
        }
        let lower = &lower[..label.len()];
        tables::LABELS
            .binary_search_by(|(candidate, _)| candidate.as_bytes().cmp(lower))
            .ok()
            .map(|position| tables::LABELS[position].1)
    }

    /// The encoding's name, for example `"windows-1252"` or `"Shift_JIS"`.
    pub fn name(self) -> &'static str {
        tables::NAMES[self as usize]
    }

    /// "Get an output encoding": UTF-8 for replacement and UTF-16BE/LE, which
    /// have no encoder, and the encoding itself otherwise.
    pub fn output_encoding(self) -> Encoding {
        match self {
            Encoding::Replacement | Encoding::Utf16Be | Encoding::Utf16Le => Encoding::Utf8,
            other => other,
        }
    }

    /// Whether the encoding is a single-byte encoding with an index (not
    /// x-user-defined, which the standard defines algorithmically).
    pub fn is_single_byte(self) -> bool {
        tables::single_byte_index(self).is_some()
    }

    /// Whether this is UTF-16BE or UTF-16LE.
    pub fn is_utf16(self) -> bool {
        matches!(self, Encoding::Utf16Be | Encoding::Utf16Le)
    }

    /// Whether every ASCII byte decodes to the same ASCII code point in the
    /// decoder's initial state. HTML's `<meta>` prescan and CSS `@charset`
    /// detection need this; it is false for UTF-16BE/LE, ISO-2022-JP and
    /// replacement.
    pub fn is_ascii_compatible(self) -> bool {
        !matches!(
            self,
            Encoding::Utf16Be | Encoding::Utf16Le | Encoding::Iso2022Jp | Encoding::Replacement
        )
    }

    /// A new instance of this encoding's decoder. Byte order marks are not
    /// examined; use [`decode`] or [`bom_sniff`] for that.
    pub fn new_decoder(self, mode: DecoderErrorMode) -> Decoder {
        Decoder::new(self, mode)
    }

    /// A new instance of the encoder of this encoding's output encoding.
    pub fn new_encoder(self) -> Encoder {
        Encoder::new(self)
    }

    /// Decode all of `bytes` with this encoding's decoder in "replacement"
    /// mode, without examining a byte order mark.
    pub fn decode_without_bom(self, bytes: &[u8]) -> String {
        let mut output = String::with_capacity(bytes.len());
        let mut decoder = self.new_decoder(DecoderErrorMode::Replacement);
        // Replacement mode never fails.
        let _ = decoder.decode(bytes, true, &mut output);
        output
    }

    /// Decode all of `bytes` with this encoding's decoder in "fatal" mode,
    /// without examining a byte order mark. `None` on the first error.
    pub fn decode_without_bom_or_fail(self, bytes: &[u8]) -> Option<String> {
        let mut output = String::with_capacity(bytes.len());
        let mut decoder = self.new_decoder(DecoderErrorMode::Fatal);
        decoder.decode(bytes, true, &mut output).ok()?;
        Some(output)
    }
}

impl core::fmt::Display for Encoding {
    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        formatter.write_str(self.name())
    }
}

/// The result of the legacy [`decode`] hook.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Decoded {
    /// The decoded text.
    pub text: String,
    /// The encoding actually used: the BOM's, or the fallback.
    pub encoding: Encoding,
    /// Whether any decoder error was replaced with U+FFFD.
    pub had_errors: bool,
}

/// "BOM sniff": the encoding a leading byte order mark names, with the BOM's
/// length in bytes.
pub fn bom_sniff(bytes: &[u8]) -> Option<(Encoding, usize)> {
    match bytes {
        [0xEF, 0xBB, 0xBF, ..] => Some((Encoding::Utf8, 3)),
        [0xFE, 0xFF, ..] => Some((Encoding::Utf16Be, 2)),
        [0xFF, 0xFE, ..] => Some((Encoding::Utf16Le, 2)),
        _ => None,
    }
}

/// The legacy "decode" hook: a byte order mark overrides `fallback`, then the
/// rest decodes in "replacement" mode.
pub fn decode(bytes: &[u8], fallback: Encoding) -> Decoded {
    let (encoding, skip) = bom_sniff(bytes).unwrap_or((fallback, 0));
    let mut text = String::with_capacity(bytes.len());
    let mut decoder = encoding.new_decoder(DecoderErrorMode::Replacement);
    // Replacement mode never fails.
    let _ = decoder.decode(&bytes[skip..], true, &mut text);
    Decoded {
        text,
        encoding,
        had_errors: decoder.had_errors(),
    }
}

/// "UTF-8 decode": strips one UTF-8 BOM, replaces errors with U+FFFD.
pub fn utf8_decode(bytes: &[u8]) -> String {
    let bytes = bytes.strip_prefix(&[0xEF, 0xBB, 0xBF]).unwrap_or(bytes);
    Encoding::Utf8.decode_without_bom(bytes)
}

/// "UTF-8 decode without BOM": replaces errors with U+FFFD.
pub fn utf8_decode_without_bom(bytes: &[u8]) -> String {
    Encoding::Utf8.decode_without_bom(bytes)
}

/// "UTF-8 decode without BOM or fail".
pub fn utf8_decode_without_bom_or_fail(bytes: &[u8]) -> Option<String> {
    Encoding::Utf8.decode_without_bom_or_fail(bytes)
}

/// The legacy "encode" hook used by HTML forms: encodes `text` with the
/// output encoding of `encoding` and writes each unmappable scalar value as
/// an HTML decimal character reference (`&#NNNN;`).
pub fn encode(text: &str, encoding: Encoding) -> Vec<u8> {
    let mut output = Vec::with_capacity(text.len());
    let mut encoder = encoding.new_encoder();
    for character in text.chars() {
        if let Err(unmappable) = encoder.encode_char(character, &mut output) {
            output.extend_from_slice(b"&#");
            output.extend_from_slice(u32::from(unmappable).to_string().as_bytes());
            output.push(b';');
        }
    }
    encoder.finish(&mut output);
    output
}

fn trim_ascii_whitespace(bytes: &[u8]) -> &[u8] {
    // ASCII whitespace per Infra: TAB, LF, FF, CR and SPACE.
    let is_space = |byte: &u8| matches!(byte, b'\t' | b'\n' | b'\x0C' | b'\r' | b' ');
    let start = bytes
        .iter()
        .position(|byte| !is_space(byte))
        .unwrap_or(bytes.len());
    let end = bytes
        .iter()
        .rposition(|byte| !is_space(byte))
        .map_or(start, |end| end + 1);
    &bytes[start..end]
}
