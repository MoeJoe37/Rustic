#!/usr/bin/env python3
"""Generate rustic-js's Unicode identifier and whitespace tables.

ECMAScript source text (ECMA-262 §12) needs three Unicode properties:
ID_Start and ID_Continue for identifier names (§12.7) and General_Category
Zs for the `USP` whitespace class (§12.2). Inputs are exact Unicode 17.0.0
files from the same pinned github.com/unicode-org/unicodetools revision as the
IDNA and text data. Every input is verified against the SHA-256 recorded in
the committed manifest before anything is generated.

Download the inputs (URLs are in SOURCES and the manifest) into one directory:

    python3 tools/generate_js_data.py --source-dir /tmp/ucd
    python3 tools/generate_js_data.py --source-dir /tmp/ucd --check

Output: crates/rustic-js/src/unicode/tables.rs (sorted inclusive ranges).
"""

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "crates/rustic-js/src/unicode/tables.rs"
MANIFEST = ROOT / "crates/rustic-js/tests/fixtures/js_data_manifest.json"

_SPEC = importlib.util.spec_from_file_location(
    "rustic_idna_data", Path(__file__).resolve().parent / "generate_idna_data.py")
idna = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(idna)

UNICODE_VERSION = idna.UNICODE_VERSION
UCD = f"{idna.UNICODE_BASE}/ucd/{UNICODE_VERSION}"

SOURCES = {
    "DerivedCoreProperties.txt": f"{UCD}/DerivedCoreProperties.txt",
    "DerivedGeneralCategory.txt": f"{UCD}/extracted/DerivedGeneralCategory.txt",
}


def data_lines(text):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(";")]


def parse_range(field):
    if ".." in field:
        lo, hi = field.split("..")
        return int(lo, 16), int(hi, 16)
    value = int(field, 16)
    return value, value


def merged(ranges):
    out = []
    for lo, hi in sorted(ranges):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def property_ranges(text, name):
    return merged(parse_range(f[0]) for f in data_lines(text) if len(f) >= 2 and f[1] == name)


def render(tables):
    lines = [
        "// @generated by tools/generate_js_data.py from Unicode "
        f"{UNICODE_VERSION}; do not edit.",
        "//",
        "// Sorted, merged, inclusive code point ranges.",
        "",
        f"pub(crate) const UNICODE_VERSION: &str = \"{UNICODE_VERSION}\";",
    ]
    for name, ranges in tables:
        lines.append("")
        lines.append(f"pub(crate) static {name}: [(u32, u32); {len(ranges)}] = [")
        for lo, hi in ranges:
            lines.append(f"    (0x{lo:04X}, 0x{hi:04X}),")
        lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true",
                        help="verify the committed output instead of writing it")
    args = parser.parse_args()

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    text = {}
    for name in SOURCES:
        data = (args.source_dir / name).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if digest != manifest["sources"][name]["sha256"]:
            sys.exit(f"{name}: SHA-256 {digest} does not match the manifest")
        text[name] = data.decode("utf-8")

    core = text["DerivedCoreProperties.txt"]
    tables = [
        ("ID_START", property_ranges(core, "ID_Start")),
        ("ID_CONTINUE", property_ranges(core, "ID_Continue")),
        ("SPACE_SEPARATOR", property_ranges(text["DerivedGeneralCategory.txt"], "Zs")),
    ]
    output = render(tables).encode("utf-8")
    digest = hashlib.sha256(output).hexdigest()
    key = str(TABLES.relative_to(ROOT))
    if args.check:
        if TABLES.read_bytes() != output or manifest["outputs"].get(key) != digest:
            sys.exit(f"{key} is stale; rerun without --check")
        print(f"{key} is current")
        return
    TABLES.parent.mkdir(parents=True, exist_ok=True)
    TABLES.write_bytes(output)
    manifest["outputs"] = {key: digest}
    MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {key} ({', '.join(f'{n}: {len(r)} ranges' for n, r in tables)})")


if __name__ == "__main__":
    main()
