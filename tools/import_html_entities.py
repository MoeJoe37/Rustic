#!/usr/bin/env python3
"""Reproduce the pinned WHATWG named-character-reference table without network I/O."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "crates/rustic-html/data"
TABLE = ROOT / "crates/rustic-html/src/entities.rs"
MANIFEST = DATA / "entities_manifest.json"


def unique_object(pairs):
    value = {}
    for key, item in pairs:
        if key in value:
            raise ValueError(f"duplicate JSON key: {key}")
        value[key] = item
    return value


def literal(value: str) -> str:
    return '"' + "".join(
        "\\" + char if char in {'"', "\\"} else char if 32 <= ord(char) < 127 else f"\\u{{{ord(char):x}}}"
        for char in value
    ) + '"'


def generate(source: bytes, version: str) -> tuple[str, str]:
    if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", version):
        raise ValueError("data version must be an explicit YYYY-MM-DD snapshot")
    data = json.loads(source, object_pairs_hook=unique_object)
    if not isinstance(data, dict) or not data:
        raise ValueError("entity data must be a nonempty object")
    entries = []
    for name, record in sorted(data.items()):
        if not re.fullmatch(r"&[A-Za-z][A-Za-z0-9]*;?", name):
            raise ValueError(f"invalid entity name: {name}")
        points = record["codepoints"]
        if (not isinstance(points, list) or not 1 <= len(points) <= 2
                or any(type(point) is not int or not 0 < point <= 0x10FFFF or 0xD800 <= point <= 0xDFFF for point in points)):
            raise ValueError(f"invalid scalar sequence: {name}")
        characters = "".join(chr(point) for point in points)
        if record["characters"] != characters:
            raise ValueError(f"codepoint/character mismatch: {name}")
        if not name.endswith(";") and data.get(name + ";", {}).get("characters") != characters:
            raise ValueError(f"legacy name has no identical terminated form: {name}")
        entries.append((name[1:], characters))
    maximum = max(len(name) for name, _ in entries)
    lines = [
        "// Generated by tools/import_html_entities.py; WHATWG snapshot " + version + ".",
        "// Source: https://html.spec.whatwg.org/entities.json; see data/WHATWG-LICENSE.md.",
        "// Standard data only; the tokenizer and lookup algorithm are original Rustic code.",
        f"pub(crate) const MAX_NAME_BYTES: usize = {maximum};", "",
        "#[rustfmt::skip]", "pub(crate) const NAMED_ENTITIES: &[(&str, &str)] = &[",
    ]
    lines.extend(f"    ({literal(name)}, {literal(value)})," for name, value in entries)
    lines.extend(["];", ""])
    rust = "\n".join(lines)
    metadata = {
        "data_version": version, "source_url": "https://html.spec.whatwg.org/entities.json",
        "source_sha256": hashlib.sha256(source).hexdigest(),
        "table_sha256": hashlib.sha256(rust.encode()).hexdigest(),
        "entries": len(entries), "legacy_entries": sum(not name.endswith(";") for name, _ in entries),
        "max_name_bytes": maximum,
        "license": "WHATWG source-code portions: BSD-3-Clause; WHATWG-LICENSE.md",
    }
    return rust, json.dumps(metadata, indent=2, sort_keys=True) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DATA / "entities.json")
    parser.add_argument("--data-version", help="explicit snapshot date when updating")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        version = args.data_version or json.loads(MANIFEST.read_text())["data_version"]
        rust, manifest = generate(args.source.read_bytes(), version)
        outputs = {TABLE: rust, MANIFEST: manifest}
        if args.check:
            if any(not path.exists() or path.read_text(encoding="utf-8") != content for path, content in outputs.items()):
                raise ValueError("stale HTML entity table/manifest")
        else:
            for path, content in outputs.items():
                path.write_text(content, encoding="utf-8", newline="\n")
        print(f"WHATWG entity table: {json.loads(manifest)['entries']} names; snapshot {version}.")
        return 0
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"HTML entity error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
