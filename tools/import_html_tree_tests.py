#!/usr/bin/env python3
"""Reproduce a conservative, offline selection from a pinned tree corpus."""

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re

from import_html_tests import literal

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "crates/rustic-html/tests/fixtures"
REVISION = "9329e64694e7835d0dcff9811e22856ef6ad16f9"
ALLOWED = frozenset("html head body p div span br hr title style script base meta link noframes plaintext basefont bgsound".split())
HEADERS = {"#errors", "#new-errors", "#document", "#document-fragment", "#script-on", "#script-off"}


def records(source: str) -> list[dict[str, str]]:
    if not source.startswith("#data\n"):
        raise ValueError("expected a #data record")
    result = []
    for block in source.split("#data\n")[1:]:
        fields: dict[str, list[str]] = {"#data": []}
        current = "#data"
        for line in block.splitlines(keepends=True):
            header = line.rstrip("\n")
            if header in HEADERS:
                if header in fields:
                    raise ValueError(f"duplicate {header} section")
                current = header
                fields[current] = []
            else:
                fields[current].append(line)
        if "#errors" not in fields or "#document" not in fields:
            raise ValueError("record lacks errors/document section")
        values = {key: "".join(lines) for key, lines in fields.items()}
        # Each field has a delimiter newline; tree records also have an empty
        # separating line. Preserve actual newlines in the Unicode input field.
        values["#data"] = values["#data"].removesuffix("\n")
        values["#document"] = values["#document"].rstrip("\n") + "\n"
        result.append(values)
    return result


def exclusion(case: dict[str, str]) -> str | None:
    if "#document-fragment" in case:
        return "fragment_context"
    if "#script-on" in case:
        return "scripting_enabled"
    if "<?" in case["#data"]:
        return "processing_instruction"
    # Conservative lexical filter, deliberately not an HTML parser. Literal
    # markup-like strings inside text/attributes can exclude extra cases.
    names = set(re.findall(r"</?([A-Za-z][A-Za-z0-9:-]*)", case["#data"]))
    output_names = set(re.findall(r"^\|\s+<([a-z][a-z0-9:-]*)>", case["#document"], re.MULTILINE))
    if any(name.lower() not in ALLOWED for name in names) or not output_names.issubset(ALLOWED):
        return "outside_element_whitelist"
    return None


def generate(raw: bytes) -> tuple[str, str]:
    cases = records(raw.decode("utf-8"))
    selected = []
    excluded: Counter[str] = Counter()
    for index, case in enumerate(cases):
        reason = exclusion(case)
        if reason:
            excluded[reason] += 1
        else:
            selected.append((index, case))
    lines = [
        "// Generated by tools/import_html_tree_tests.py; do not edit expectations.",
        f"// html5lib/html5lib-tests {REVISION}; MIT notice: HTML5LIB-LICENSE.md.",
        "#[rustfmt::skip]",
        "pub const TREE_CASES: &[(usize, &str, &str)] = &[",
    ]
    for index, case in selected:
        lines.append(f"    ({index}, {literal(case['#data'])}, {literal(case['#document'])}),")
    lines.extend([
        "];", "", f"pub const TREE_SPLITS: usize = {sum(len(c['#data'].encode('utf-8')) + 1 for _, c in selected)};", "",
    ])
    rust = "\n".join(lines)
    manifest = {
        "upstream_repository": "https://github.com/html5lib/html5lib-tests",
        "upstream_revision": REVISION,
        "upstream_path": "tree-construction/tests1.dat",
        "source_path": "tree_tests1.dat",
        "source_sha256": hashlib.sha256(raw).hexdigest(),
        "fixture_sha256": hashlib.sha256(rust.encode()).hexdigest(),
        "license": "MIT; HTML5LIB-LICENSE.md",
        "selection_policy": "closed-element-whitelist-no-fragments-scripting-disabled-v1",
        "allowed_element_names": sorted(ALLOWED),
        "upstream_cases": len(cases),
        "selected_cases": len(selected),
        "selected_array_indices": [i for i, _ in selected],
        "excluded_cases": sum(excluded.values()),
        "exclusion_reasons": dict(sorted(excluded.items())),
        "checked": ["complete tree and attributes", "every two-chunk byte split", "one-byte feeds"],
        "not_checked": ["upstream parse errors/positions", "compatibility mode", "excluded records", "full tree construction conformance"],
        "input_adapter": "Unicode fixture stream encoded as UTF-8 after an explicit transport BOM",
    }
    return rust, json.dumps(manifest, indent=2, sort_keys=True) + "\n"


def check() -> None:
    rust, manifest = generate((FIXTURES / "tree_tests1.dat").read_bytes())
    for name, content in [("tree_cases.rs", rust), ("tree_manifest.json", manifest)]:
        if (FIXTURES / name).read_text(encoding="utf-8") != content:
            raise ValueError(f"{name} differs; regenerate deliberately")
    if not (FIXTURES / "HTML5LIB-LICENSE.md").is_file():
        raise ValueError("missing html5lib data license")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        check()
    else:
        rust, manifest = generate((FIXTURES / "tree_tests1.dat").read_bytes())
        (FIXTURES / "tree_cases.rs").write_text(rust, encoding="utf-8")
        (FIXTURES / "tree_manifest.json").write_text(manifest, encoding="utf-8")
    metadata = json.loads((FIXTURES / "tree_manifest.json").read_text())
    print(f"Tree corpus: {metadata['selected_cases']}/{metadata['upstream_cases']} selected records")


if __name__ == "__main__":
    main()
