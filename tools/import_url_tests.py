#!/usr/bin/env python3
"""Generate an offline Rust URL fixture subset from a pinned WPT source file."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "crates/rustic-url/tests/fixtures"
FIELDS = (
    "href", "protocol", "username", "password", "host", "hostname", "port",
    "pathname", "search", "hash",
)
POLICY = "ascii-input-and-base-without-blob-or-percent-encoded-non-ascii-v2"


def exclusion(value: str) -> str | None:
    if not value.isascii():
        return "non_ascii_input_or_base"
    # This deliberately conservative subset excludes encoded non-ASCII bytes in
    # any component, including paths, so it never needs Unicode IDNA processing.
    if re.search(r"%[89a-fA-F][0-9a-fA-F]", value):
        return "percent_encoded_non_ascii"
    cleaned = value.strip("".join(chr(code) for code in range(33)))
    cleaned = cleaned.replace("\t", "").replace("\r", "").replace("\n", "")
    match = re.match(r"([a-zA-Z][a-zA-Z0-9+.-]*):", cleaned)
    if match and match.group(1).lower() == "blob":
        return "blob"
    return None


def literal(value: str) -> str:
    pieces = ['"']
    for char in value:
        if char == '"':
            pieces.append('\\"')
        elif char == "\\":
            pieces.append("\\\\")
        elif ord(char) < 32 or ord(char) == 127:
            pieces.append(f"\\u{{{ord(char):x}}}")
        elif 0xD800 <= ord(char) <= 0xDFFF:
            raise ValueError("surrogates cannot appear in this ASCII fixture subset")
        else:
            pieces.append(char)
    return "".join(pieces) + '"'


def optional(value: str | None) -> str:
    return "None" if value is None else f"Some({literal(value)})"


def generate(source: bytes, revision: str) -> tuple[str, str]:
    upstream = json.loads(source)
    if not isinstance(upstream, list):
        raise ValueError("WPT URL source must be an array")
    lines = [
        "// Generated by tools/import_url_tests.py. Do not edit by hand.",
        f"// WPT revision: {revision}; BSD-3-Clause, see WPT-LICENSE.md.",
        "use super::{Case, Expected};",
        "",
        "#[rustfmt::skip]",
        "pub const CASES: &[Case] = &[",
    ]
    total = selected = positives = negatives = 0
    excluded: dict[str, int] = {}
    indices = []
    for index, case in enumerate(upstream):
        if not isinstance(case, dict):
            continue  # Upstream's section-description strings are not test cases.
        total += 1
        reason = exclusion(case["input"]) or exclusion(case.get("base") or "")
        if reason:
            excluded[reason] = excluded.get(reason, 0) + 1
            continue
        selected += 1
        indices.append(index)
        prefix = f"Case {{ index: {index}, input: {literal(case['input'])}, base: {optional(case.get('base'))}, expected: "
        if case.get("failure"):
            negatives += 1
            lines.append(f"    {prefix}None }},")
        else:
            positives += 1
            fields = ", ".join(f"{field}: {literal(case[field])}" for field in FIELDS)
            fields += f", origin: {optional(case.get('origin'))}"
            lines.append(f"    {prefix}Some(Expected {{ {fields} }}) }},")
    lines.extend([
        "];", "",
        f"pub const SELECTED: usize = {selected};",
        f"pub const POSITIVE: usize = {positives};",
        f"pub const NEGATIVE: usize = {negatives};", "",
    ])
    rust = "\n".join(lines)
    blob = hashlib.sha1(b"blob " + str(len(source)).encode() + b"\0" + source).hexdigest()
    manifest = {
        "upstream_repository": "web-platform-tests/wpt",
        "upstream_revision": revision,
        "upstream_path": "url/resources/urltestdata.json",
        "source_url": f"https://github.com/web-platform-tests/wpt/blob/{revision}/url/resources/urltestdata.json",
        "source_git_blob": blob,
        "source_sha256": hashlib.sha256(source).hexdigest(),
        "fixture_sha256": hashlib.sha256(rust.encode()).hexdigest(),
        "selection_policy": POLICY,
        "upstream_cases": total,
        "selected_cases": selected,
        "positive_cases": positives,
        "negative_cases": negatives,
        "excluded_cases": total - selected,
        "exclusion_reasons": excluded,
        "selected_array_indices": indices,
        "checked_fields": list(FIELDS) + ["origin when supplied upstream"],
        "not_checked": ["URLSearchParams", "setters", "validation-error diagnostics (upstream records none)", "legacy query encodings"],
        "license": "BSD-3-Clause; WPT-LICENSE.md",
    }
    return rust, json.dumps(manifest, indent=2, sort_keys=True) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--revision", required=True)
    parser.add_argument("--check", action="store_true", help="verify outputs without changing files")
    args = parser.parse_args()
    if not re.fullmatch(r"[0-9a-f]{40}", args.revision):
        parser.error("--revision must be the full upstream commit SHA")
    rust, manifest = generate(args.source.read_bytes(), args.revision)
    outputs = {DESTINATION / "wpt_cases.rs": rust, DESTINATION / "wpt_manifest.json": manifest}
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, value in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != value]
        if stale:
            print("Stale WPT fixture output: " + ", ".join(stale), file=sys.stderr)
            return 1
    else:
        DESTINATION.mkdir(parents=True, exist_ok=True)
        for path, value in outputs.items():
            path.write_text(value, encoding="utf-8", newline="\n")
    summary = json.loads(manifest)
    print(f"WPT URL subset: {summary['selected_cases']} selected / {summary['upstream_cases']} upstream; "
          f"{summary['positive_cases']} positive, {summary['negative_cases']} negative, {summary['excluded_cases']} excluded.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
