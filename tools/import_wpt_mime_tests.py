#!/usr/bin/env python3
"""Generate rustic-net's MIME and Content-Type cases from pinned WPT data.

The three JSON files are vendored, unmodified, under
`crates/rustic-net/tests/fixtures/wpt/` from web-platform-tests/wpt at
`WPT_REVISION`. Each is verified against its pinned SHA-256, then turned into
Rust constants in `crates/rustic-net/tests/fixtures/mime_cases.rs`, and
`manifest.json` records the digests that `tools/check_repository.py` checks.
Every record is selected; there are no exclusions.

    python3 tools/import_wpt_mime_tests.py           # regenerate
    python3 tools/import_wpt_mime_tests.py --check   # fail if outputs differ
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "crates/rustic-net/tests/fixtures"
WPT_REVISION = "8c17bfeb3e66a2986be16b0e004f85ace68db647"
SOURCES = {
    "mime-types.json": (
        "mimesniff/mime-types/resources/mime-types.json",
        "016d3dd91b647e03af2a69c7ec241bf787df8bffe7953018fe566e8ec5d7b822",
    ),
    "generated-mime-types.json": (
        "mimesniff/mime-types/resources/generated-mime-types.json",
        "20924495060ac9633f10d57a326b95a5987863f27c5d4765b13b744304b33fed",
    ),
    "content-types.json": (
        "fetch/content-type/resources/content-types.json",
        "ad2e2dfc6b3f6501911e4990f3adb1bf238e6910f56b3206fd8d7e8c83459974",
    ),
    "data-urls.json": (
        "fetch/data-urls/resources/data-urls.json",
        "b3be3d6e1d0eb7f1b5b20d7410d30cb76216d41c9fe3d8364446abecff88bba5",
    ),
    "base64.json": (
        "fetch/data-urls/resources/base64.json",
        "0cdb75b4fcc46e4a6caa0e3b0005157a0d0be03e00bcf7b7054a045b1267568d",
    ),
}


def rust_str(value):
    out = []
    for character in value:
        if character in '"\\':
            out.append("\\" + character)
        elif " " <= character <= "~":
            out.append(character)
        else:
            out.append("\\u{%x}" % ord(character))
    return '"' + "".join(out) + '"'


def rust_opt(value):
    return "None" if value is None else "Some(%s)" % rust_str(value)


def load(name):
    path = FIXTURES / "wpt" / name
    data = path.read_bytes()
    expected = SOURCES[name][1]
    if hashlib.sha256(data).hexdigest() != expected:
        raise SystemExit(f"{path}: digest differs from the pinned WPT source")
    return json.loads(data)


def generate():
    mime = [record for record in load("mime-types.json") if isinstance(record, dict)]
    generated = load("generated-mime-types.json")
    content = load("content-types.json")
    lines = [
        f"// Generated by tools/import_wpt_mime_tests.py from web-platform-tests/wpt {WPT_REVISION}.",
        "// Do not edit. WPT is BSD-3-Clause; see WPT-LICENSE.md.",
        "",
        "/// mimesniff/mime-types/resources/mime-types.json: (input, serialization",
        "/// or failure, encoding name from the charset parameter).",
        "pub const MIME_TYPES: &[(&str, Option<&str>, Option<&str>)] = &[",
    ]
    lines += [
        f"    ({rust_str(r['input'])}, {rust_opt(r['output'])}, {rust_opt(r.get('encoding'))}),"
        for r in mime
    ]
    lines += [
        "];",
        "",
        "/// mimesniff/mime-types/resources/generated-mime-types.json: (input,",
        "/// serialization or failure).",
        "pub const GENERATED_MIME_TYPES: &[(&str, Option<&str>)] = &[",
    ]
    lines += [f"    ({rust_str(r['input'])}, {rust_opt(r['output'])})," for r in generated]
    lines += [
        "];",
        "",
        "/// fetch/content-type/resources/content-types.json: (Content-Type header",
        "/// lines, document encoding or none, extracted MIME type serialization).",
        "pub const CONTENT_TYPES: &[(&[&str], Option<&str>, Option<&str>)] = &[",
    ]
    for r in content:
        values = ", ".join(rust_str(value) for value in r["contentType"])
        lines.append(f"    (&[{values}], {rust_opt(r['encoding'])}, {rust_opt(r['mimeType'])}),")
    lines += ["];", ""]
    data_urls = [r for r in load("data-urls.json") if isinstance(r, list)]
    base64 = [r for r in load("base64.json") if isinstance(r, list)]
    lines += [
        "/// fetch/data-urls/resources/data-urls.json: (URL, MIME type",
        "/// serialization or failure, body bytes).",
        "pub const DATA_URLS: &[(&str, Option<&str>, &[u8])] = &[",
    ]
    for r in data_urls:
        body = ", ".join(str(b) for b in (r[2] if len(r) > 2 else []))
        lines.append(f"    ({rust_str(r[0])}, {rust_opt(r[1])}, &[{body}]),")
    lines += [
        "];",
        "",
        "/// fetch/data-urls/resources/base64.json: (input, decoded bytes or",
        "/// failure).",
        "pub const BASE64: &[(&str, Option<&[u8]>)] = &[",
    ]
    for r in base64:
        output = "None" if r[1] is None else "Some(&[%s])" % ", ".join(str(b) for b in r[1])
        lines.append(f"    ({rust_str(r[0])}, {output}),")
    lines += ["];", ""]
    fixture = "\n".join(lines).encode()
    manifest = {
        "upstream_repository": "web-platform-tests/wpt",
        "upstream_revision": WPT_REVISION,
        "license": "BSD-3-Clause; WPT-LICENSE.md",
        "generator": "tools/import_wpt_mime_tests.py",
        "selection_policy": "all-records",
        "sources": [
            {
                "path": f"crates/rustic-net/tests/fixtures/wpt/{name}",
                "upstream_path": upstream,
                "sha256": digest,
            }
            for name, (upstream, digest) in SOURCES.items()
        ],
        "cases": {
            "MIME_TYPES": len(mime),
            "GENERATED_MIME_TYPES": len(generated),
            "CONTENT_TYPES": len(content),
            "DATA_URLS": len(data_urls),
            "BASE64": len(base64),
        },
        "fixture": "crates/rustic-net/tests/fixtures/mime_cases.rs",
        "fixture_sha256": hashlib.sha256(fixture).hexdigest(),
    }
    return fixture, (json.dumps(manifest, indent=2) + "\n").encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if outputs differ")
    args = parser.parse_args()
    fixture, manifest = generate()
    outputs = {FIXTURES / "mime_cases.rs": fixture, FIXTURES / "manifest.json": manifest}
    if args.check:
        stale = [path for path, data in outputs.items() if not path.exists() or path.read_bytes() != data]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale; rerun tools/import_wpt_mime_tests.py", file=sys.stderr)
        return 1 if stale else 0
    for path, data in outputs.items():
        path.write_bytes(data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
